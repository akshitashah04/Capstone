import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const dataRoot = new URL('../../frontend/public/data/', import.meta.url);
const manifestUrl = new URL('manifest.json', dataRoot);
const manifest = JSON.parse(await readFile(manifestUrl, 'utf8'));
const digest = bytes => createHash('sha256').update(bytes).digest('hex');

async function readIds(name, expectedCount) {
  const bytes = await readFile(new URL(name, dataRoot));
  const expected = manifest.files[name];
  if (digest(bytes) !== expected.sha256 || bytes.length !== expected.bytes) {
    throw new Error(`${name} does not match its manifest.`);
  }
  const ids = JSON.parse(bytes.toString('utf8')).map(book => book.id);
  if (ids.length !== expectedCount || ids.some(id => typeof id !== 'string' || !id) ||
      new Set(ids).size !== ids.length) {
    throw new Error(`${name} has missing or duplicate book IDs.`);
  }
  return ids;
}

const base = await readIds('catalog.json', manifest.books);
const baseSha = manifest.files['catalog.json'].sha256;
const refresh = process.argv.includes('--refresh-manifest');
if (refresh) {
  const bytes = await readFile(new URL('multilingual.json', dataRoot));
  manifest.supplemental_books = JSON.parse(bytes.toString('utf8')).length;
  manifest.files['multilingual.json'] = { bytes: bytes.length, sha256: digest(bytes) };
  manifest.catalog_sha256 = digest(baseSha + manifest.files['multilingual.json'].sha256);
}
const supplementFile = manifest.files['multilingual.json'];
const supplement = supplementFile
  ? await readIds('multilingual.json', manifest.supplemental_books) : [];
const combined = [...base, ...supplement];
const currentSha = supplementFile ? digest(baseSha + supplementFile.sha256) : baseSha;
if (currentSha !== (manifest.catalog_sha256 ?? baseSha) || new Set(combined).size !== combined.length) {
  throw new Error('The combined catalog checksum or IDs are invalid.');
}

const source = '// Generated by scripts/sync-catalog.mjs from the checked browser sample.\n' +
  `const BASE_BOOK_IDS = ${JSON.stringify(base)};\n` +
  `export const CATALOG_SHA256 = ${JSON.stringify(currentSha)};\n` +
  `export const KNOWN_BOOK_IDS = new Set([...BASE_BOOK_IDS, ...${JSON.stringify(supplement)}]);\n` +
  'export const CATALOG_BOOK_IDS = new Map([\n' +
  (supplementFile ? `  [${JSON.stringify(baseSha)}, new Set(BASE_BOOK_IDS)],\n` : '') +
  '  [CATALOG_SHA256, KNOWN_BOOK_IDS],\n]);\n';
if (refresh) await writeFile(manifestUrl, JSON.stringify(manifest, null, 2) + '\n');
await writeFile(new URL('../worker/known-books.js', import.meta.url), source);
console.log(`Synced ${combined.length} book IDs from catalog ${currentSha.slice(0, 12)}.`);
